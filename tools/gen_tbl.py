CONTROLS = {
    0x00: "end", 0x01: "page", 0x02: "c02", 0x03: "c03", 0x04: "c04", 0x05: "c05", 0x06: "c06", 0x07: "c07",
    0x08: "c08", 0x09: "c09", 0x0A: "c0A", 0x0B: "c0B", 0x0C: "wait", 0x0D: "n", 0x0E: "c0E", 0x0F: "c0F",
}


def lines():
    assert len(GLYPHS) == 0x184, len(GLYPHS)
    out = ["# Generated by tools/gen_tbl.py - edit that file, not this one."]
    out += [f"{c:02X}={{{n}}}" for c, n in sorted(CONTROLS.items())]
    out += [f"{i + 0x10:02X}={g}" for i, g in enumerate(GLYPHS[:0x70])]
    out += [f"{0x80 | i >> 8:02X}{i & 0xFF:02X}={g}" for i, g in enumerate(GLYPHS)]
    return out


if __name__ == "__main__":
    p = ROOT / "tbl" / "jp.tbl"
    p.parent.mkdir(exist_ok=True)
    p.write_text("\n".join(lines()) + "\n", encoding="utf-8", newline="\n")
    print(p)
