"""font.py: the dialogue VWF font (fonts/vwf.txt) -> glyph bytes, advance widths, tbl/en.tbl, pixel widths.

    python -X utf8 tools/font.py            write tbl/en.tbl (control codes from tbl/jp.tbl + one row per glyph)
    python -X utf8 tools/font.py --check    exit 1 if tbl/en.tbl is stale

Glyph i is drawn from the game's font slot i ($84:808C + i*22, 11 rows x 2 bytes big-endian, MSB = left pixel)
and is text code i + 0x10 (one byte). asm/vwf.asm incbins build/vwf_font.bin and build/vwf_widths.bin.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "fonts" / "vwf.txt"
JP_TBL = ROOT / "tbl" / "jp.tbl"
EN_TBL = ROOT / "tbl" / "en.tbl"
ROWS, CODE0, MAX_GLYPHS = 11, 0x10, 0x70  # one-byte codes 10-7F


def load(path=SRC):
    """[(char, [11 row ints, MSB = left pixel], advance)] in file order."""
    glyphs, cur = [], None
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if line.startswith("== "):
            parts = line[3:].split()
            ch = " " if parts[0] == r"\s" else parts[0]
            cur = [ch, [], int(parts[1]) if len(parts) > 1 else None]
            glyphs.append(cur)
        elif cur and line:  # art rows; '#' lines before the first glyph are comments
            if line.strip("#.") or len(cur[1]) == ROWS:
                raise ValueError(f"{path.name}:{n}: glyph {cur[0]!r}: bad row or more than {ROWS} rows")
            cur[1].append(line)
    out = []
    for ch, art, adv in glyphs:
        if len(ch) != 1:
            raise ValueError(f"glyph name {ch!r} is not one character")
        rows = [sum(1 << (15 - x) for x, c in enumerate(r) if c == "#") for r in art] + [0] * (ROWS - len(art))
        ink = max((len(r.rstrip(".")) for r in art), default=0)
        if ink > 15:
            raise ValueError(f"glyph {ch!r} wider than 15 px")
        out.append((ch, rows, adv if adv is not None else ink + 1))
    if len(out) > MAX_GLYPHS:
        raise ValueError(f"{len(out)} glyphs, one-byte codes hold {MAX_GLYPHS}")
    return out


def glyph_bytes(glyphs):
    return b"".join(r.to_bytes(2, "big") for _, rows, _ in glyphs for r in rows)


def widths(glyphs):
    return bytes(adv for _, _, adv in glyphs)


def advance_map(glyphs):
    return {ch: adv for ch, _, adv in glyphs}


def text_width(text, adv):
    """Pixel width of one line of plain text (no control codes)."""
    return sum(adv[c] for c in text)


def tbl_lines(glyphs):
    ctrl = [ln for ln in JP_TBL.read_text(encoding="utf-8").splitlines() if "={" in ln]
    rows = [f"{CODE0 + i:02X}={r'\s' if ch == ' ' else ch}" for i, (ch, _, _) in enumerate(glyphs)]
    return ["# generated by tools/font.py from fonts/vwf.txt; do not edit"] + ctrl + rows


def main():
    text = "\n".join(tbl_lines(load())) + "\n"
    if "--check" in sys.argv:
        ok = EN_TBL.is_file() and EN_TBL.read_text(encoding="utf-8") == text
        print("tbl/en.tbl " + ("current" if ok else "STALE: run tools/font.py"))
        return 0 if ok else 1
    EN_TBL.write_text(text, encoding="utf-8", newline="\n")
    print(f"tbl/en.tbl: {len(load())} glyphs")


if __name__ == "__main__":
    sys.exit(main())
